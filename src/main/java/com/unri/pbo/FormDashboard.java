    @SuppressWarnings("unchecked")
    public void loadDataDashboard() {
        java.text.NumberFormat kursIDR = java.text.NumberFormat.getCurrencyInstance(new java.util.Locale("id", "ID"));
        String namaKasir = (DataStore.currentUser == null || DataStore.currentUser.isEmpty()) 
                ? "Admin" : DataStore.currentUser;

        try (java.sql.Connection conn = DataStore.getConnection()) {
            // 1. Pendapatan Hari Ini -> jLabel2
            String sqlPendapatan = "SELECT COALESCE(SUM(total_harga), 0) AS total FROM transaksi WHERE jenis = 'PENJUALAN' AND DATE(tanggal) = CURDATE()";
            try (java.sql.Statement st = conn.createStatement(); java.sql.ResultSet rs = st.executeQuery(sqlPendapatan)) {
                if (rs.next()) {
                    jLabel2.setText(kursIDR.format(rs.getDouble("total")));
                }
            }

            // 2. Total Transaksi -> jLabel6
            String sqlTotalTrx = "SELECT COUNT(*) AS jml FROM transaksi";
            try (java.sql.Statement st = conn.createStatement(); java.sql.ResultSet rs = st.executeQuery(sqlTotalTrx)) {
                if (rs.next()) {
                    jLabel6.setText(String.valueOf(rs.getInt("jml")));
                }
            }

            // 3. Stok Menipis (stok <= 5) -> jLabel4
            String sqlStokMenipis = "SELECT COUNT(*) AS jml FROM produk WHERE stok <= 5";
            try (java.sql.Statement st = conn.createStatement(); java.sql.ResultSet rs = st.executeQuery(sqlStokMenipis)) {
                if (rs.next()) {
                    jLabel4.setText(String.valueOf(rs.getInt("jml")));
                }
            }

            // 4. Total Produk -> jLabel8
            String sqlTotalProduk = "SELECT COUNT(*) AS jml FROM produk";
            try (java.sql.Statement st = conn.createStatement(); java.sql.ResultSet rs = st.executeQuery(sqlTotalProduk)) {
                if (rs.next()) {
                    jLabel8.setText(String.valueOf(rs.getInt("jml")));
                }
            }

            // 5. Isi Tabel Transaksi Terbaru -> jTable1 (Mengambil dari DataStore.daftarRiwayat seperti PanelRiwayat)
            DataStore.loadRiwayatFromDB();
            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
            model.setRowCount(0);

            java.time.format.DateTimeFormatter fmt = java.time.format.DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");
        int batas = Math.min(DataStore.daftarRiwayat.size(), 10);
        for (int i = 0; i < batas; i++) {
            RiwayatTransaksiToko t = DataStore.daftarRiwayat.get(i);
            String tglStr = (t.getWaktu() != null) ? t.getWaktu().format(fmt) : "-";
            String keterangan = t.getJenisTransaksi() + " - " + t.getDetailAktivitas() + " (" + t.getJumlahBaru() + " pcs)";

            model.addRow(new Object[]{
                t.getIdTransaksi(),
                tglStr,
                t.getPengguna(),
                DataStore.formatRupiah(t.getTotalBaru().doubleValue()),
                keterangan
            });
        }

        } catch (java.sql.SQLException e) {
            System.err.println("Gagal memuat data dashboard: " + e.getMessage());
        }
    }
